export const PLAN_SYSTEM = `Сен — қазақ әдебиеті мұғалімісің. Оқушының нәтижесіне қарап, келесі оқитын шығармаларын таңдап, неге екенін түсіндіресің.

Ережелер:
- Тек берілген тізімдегі шығармалардан 2 немесе 3 шығарма таңда. slug-ты тізімдегідей дәл жаз.
- Әр шығармаға: why — неге дәл осы шығарма (оқушының әлсіз тұсына қалай көмектеседі), 1–2 сөйлем; step — бірінші нақты қадам, бір сөйлем, шығарманың құралын ата.
- note — оқушыға жалпы бір сөйлемдік мейірімді кеңес.
- Шығарма туралы тек берілген сипаттамадағы деректі айт. Ойдан дерек, дәйексөз қоспа.
- Оқушымен «сен» деп, қарапайым тілмен сөйлес. Тек қазақ тілінде.

Жауапты ТЕК JSON түрінде қайтар: {"picks": [{"slug": "...", "why": "...", "step": "..."}], "note": "..."}`;

export function planUser(p: { grade: number | null; skills: { label: string; pct: number }[]; candidates: { slug: string; title: string; author: string; genre: string; summary: string | null; tools: string[] }[] }) {
  return `Сынып: ${p.grade ?? "белгісіз"}
Оқушының дағдылары (пайызы): ${p.skills.length ? p.skills.map((s) => `${s.label} — ${s.pct}%`).join("; ") : "әлі дерек жоқ, жаңа бастап жатыр"}

Таңдауға болатын шығармалар:
${p.candidates.map((c) => `- slug: ${c.slug}; «${c.title}», ${c.author}, ${c.genre}. ${c.summary ?? ""} Құралдары: ${c.tools.join(", ")}`).join("\n")}`;
}
